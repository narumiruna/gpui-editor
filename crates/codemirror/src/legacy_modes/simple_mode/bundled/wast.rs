use super::{SimpleRule, next, styled};

pub(super) fn states() -> [(&'static str, Vec<SimpleRule>); 2] {
    [
        (
            "start",
            vec![
                styled(&KEYWORDS.join("|"), "keyword"),
                styled(
                    r"\b((any|data|eq|extern|i31|func)ref|[fi](32|64)|i(8|16))\b",
                    "atom",
                ),
                styled(r"\b(funcref|externref|[fi](32|64))\b", "atom"),
                styled(r"\$([a-zA-Z0-9_`+\-*/\\\^~=<>!?@#$%&|:.]+)", "variable"),
                styled(
                    r#""(?:[^"\\\x00-\x1f\x7f]|\\[nt\\'"]|\\[0-9a-fA-F][0-9a-fA-F])*""#,
                    "string",
                ),
                next(styled(r"\(;.*?", "comment"), "comment"),
                styled(r";;.*$", "comment"),
                SimpleRule {
                    indent: true,
                    ..SimpleRule::new(r"\(")
                },
                SimpleRule {
                    dedent: true,
                    ..SimpleRule::new(r"\)")
                },
            ],
        ),
        (
            "comment",
            vec![
                next(styled(r".*?;\)", "comment"), "start"),
                styled(".*", "comment"),
            ],
        ),
    ]
}

