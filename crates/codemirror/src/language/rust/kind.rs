macro_rules! node_kinds {
    ($($kind:ident => $name:literal,)*) => {
        /// A visible node type in the upstream Rust grammar.
        #[derive(Clone, Copy, Debug, Eq, PartialEq)]
        #[non_exhaustive]
        pub enum RustNodeKind { $($kind,)* }

        impl RustNodeKind {
            /// The name in the upstream syntax tree.
            pub const fn name(self) -> &'static str {
                match self { $(Self::$kind => $name,)* }
            }

            pub(super) fn from_name(name: &str) -> Self {
                match name {
                    $($name => Self::$kind,)*
                    _ => unreachable!("unknown node in the pinned Rust grammar: {name}"),
                }
            }
        }
    };
}

