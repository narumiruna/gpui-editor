//! Exact recovery records from the tarballs in docs/codemirror-upstream.json:
//! @lezer/json 1.0.3, lr 1.4.13, common 1.5.7, highlight 1.2.5;
//! @codemirror/lang-json 6.0.2, language 6.13.1, state 6.7.6.
//! The oracle used `ensureSyntaxTree`, `highlightTree` with named tags,
//! `foldInside`, `foldable`, `getIndentation`, and `jsonParseLinter` in Node
//! 26.10.0. It used `Text.of(source.split('\n'))` to retain raw CRLF, excluded
//! CRLF from the line ranges passed to `foldable`, and converted every UTF-16
//! offset to bytes. It replaced lone surrogates in lint messages with `�`.

use gpui_editor_codemirror::{
    Change, ChangeSet, Text,
    language::{
        IndentOptions, StreamSettings,
        json::{JsonDocument, JsonNodeKind, json_parse_linter},
    },
    lint::Severity,
};
use serde_json::{Value, json};

const FIXTURES: &str = include_str!("fixtures/json_recovery.jsonl");
// Generated by fixtures/json_oracle.mjs from a sequence of EditorState edits.
const REPAIR: &str = include_str!("fixtures/json_repair.jsonl");
const WRONG_CLOSER: &str = "wrong closer before valid array closer on CRLF";

fn cases() -> impl Iterator<Item = Value> {
    FIXTURES
        .lines()
        .map(|line| serde_json::from_str(line).unwrap())
}

fn check(doc: &JsonDocument, case: &Value) {
    let name = case["name"].as_str().unwrap();
    let source = case["source"].as_str().unwrap();
    assert_eq!(doc.text().as_str(), source, "{name}");

    let mut nodes = Vec::new();
    let mut node_folds = Vec::new();
    let mut pending = vec![(0, doc.root())];
    while let Some((depth, node)) = pending.pop() {
        let range = node.range();
        assert!(source.get(range.clone()).is_some(), "{name}: {range:?}");
        nodes.push(json!([depth, node.kind().name(), range.start, range.end]));
        if let Some(fold) = node.fold_range() {
            node_folds.push([fold.start, fold.end]);
        }
        pending.extend(node.children().rev().map(|child| (depth + 1, child)));
    }
    assert_eq!(doc.nodes().len(), nodes.len(), "{name}");
    assert_eq!(json!(nodes), case["nodes"], "nodes: {name}");
    assert_eq!(json!(node_folds), case["nodeFolds"], "node folds: {name}");

    let highlights: Vec<_> = doc
        .highlights(0..source.len())
        .unwrap()
        .map(|span| {
            let [tag] = span.tags else {
                panic!("{name}: {:?}", span.tags)
            };
            json!([span.range.start, span.range.end, tag.name()])
        })
        .collect();
    assert_eq!(json!(highlights), case["highlights"], "highlights: {name}");

    let mut folds = Vec::new();
    let mut indents = Vec::new();
    for number in 1..=doc.text().line_count() {
        let line = doc.text().line(number).unwrap();
        folds.push(
            doc.foldable(line.range.start, line.range.end)
                .map(|fold| [fold.start, fold.end]),
        );
        indents.push(doc.indentation(
            line.range.start,
            StreamSettings::default(),
            IndentOptions::default(),
        ));
    }
    assert_eq!(json!(folds), case["folds"], "line folds: {name}");
    assert_eq!(json!(indents), case["indents"], "indentation: {name}");

    let lint: Vec<_> = json_parse_linter(doc.text())
        .iter()
        .map(|error| {
            assert_eq!(error.severity, Severity::Error, "lint severity: {name}");
            json!([error.range.start, error.range.end, "error", error.message])
        })
        .collect();
    assert_eq!(json!(lint), case["lint"], "lint: {name}");
}

fn check_recovered(doc: &JsonDocument, case: &Value) {
    check(doc, case);
    let name = case["name"].as_str().unwrap();
    assert!(doc.diagnostic().is_some(), "{name}");
    assert_eq!(doc.reuse_stats(), Default::default(), "{name}");
    assert_eq!(doc.reused_suffix_actions(), 0, "{name}");
}

#[test]
fn matches_pinned_malformed_trees_and_services() {
    for case in cases() {
        let doc = JsonDocument::parse(Text::new(case["source"].as_str().unwrap()));
        check_recovered(&doc, &case);
    }
}

#[test]
fn uses_the_same_recovery_after_editing_a_strict_tree() {
    let case = cases().find(|case| case["name"] == WRONG_CLOSER).unwrap();
    let source = case["source"].as_str().unwrap();
    let tail = source.find('}').unwrap();
    let valid = format!("{}{{}}]\n", &source[..tail]);
    let doc = JsonDocument::parse(Text::new(&valid));
    assert!(doc.diagnostic().is_none());

    let changes = ChangeSet::single(Change::new(tail..valid.len(), &source[tail..])).unwrap();
    let recovered = doc.reparse(&changes).unwrap();
    check_recovered(&recovered, &case);

    let repair = ChangeSet::single(Change::new(tail..source.len(), &valid[tail..])).unwrap();
    let repaired = recovered.reparse(&repair).unwrap();
    assert_eq!(repaired.text(), doc.text());
    assert!(repaired.diagnostic().is_none());
}

#[test]
fn only_strict_repair_reuses_the_prefix_from_a_recovered_document() {
    let mut steps = REPAIR
        .lines()
        .map(|line| serde_json::from_str::<Value>(line).unwrap());
    let initial = steps.next().unwrap();
    let mut doc = JsonDocument::parse(Text::new(initial["source"].as_str().unwrap()));
    check(&doc, &initial);
    assert!(doc.diagnostic().is_none());

    for case in steps {
        let (start, end, insert): (usize, usize, String) =
            serde_json::from_value(case["change"].clone()).unwrap();
        let edit = ChangeSet::single(Change::new(start..end, &insert)).unwrap();
        let next = doc.reparse(&edit).unwrap();
        let fresh = JsonDocument::parse(next.text().clone());
        check(&fresh, &case);
        if case["name"] == "repair separator" {
            check(&next, &case);
            assert!(next.diagnostic().is_none());
            let reuse = next.reuse_stats();
            assert!(reuse.nodes_reused > 20, "{reuse:?}");
            assert!((64..=start).contains(&reuse.resumed_at), "{reuse:?}");
            assert_eq!(next.reused_suffix_actions(), 0);

            // Moving the prefix leaves only a shifted suffix candidate.
            let shifted = ChangeSet::new(vec![
                Change::new(0..0, " "),
                Change::new(start..end, insert),
            ])
            .unwrap();
            let shifted = doc.reparse(&shifted).unwrap();
            assert!(shifted.diagnostic().is_none());
            assert_eq!(shifted.reuse_stats(), Default::default());
            assert_eq!(shifted.reused_suffix_actions(), 0);
        } else {
            check_recovered(&next, &case);
            let diagnostic = next.diagnostic().unwrap();
            let expected = fresh.diagnostic().unwrap();
            assert_eq!(diagnostic.range, expected.range);
            assert_eq!(diagnostic.message, expected.message);
        }
        doc = next;
    }
}

#[test]
fn recovers_long_invalid_string_without_losing_the_suffix() {
    // The unmatched quote makes the LR tokenizer scan long suffixes at many
    // offsets. The local scanner can reuse the first failed string scan.
    let rows = 9;
    let prefix = format!("[\r\n{}", "  {\"x\":\"😀\"},\r\n".repeat(rows));
    let bad = r#"\""#.repeat(2_048);
    let source = format!("{prefix}\"{bad}\r\n  42]");
    let doc = JsonDocument::parse(Text::new(&source));
    let end = prefix.len() + 1 + bad.len();
    let array = doc.root().children().next().unwrap();
    assert_eq!(array.kind(), JsonNodeKind::Array);
    assert_eq!(array.range(), 0..source.len());
    assert_eq!(
        array
            .children()
            .skip(1 + 2 * rows)
            .map(|node| (node.kind(), node.range()))
            .collect::<Vec<_>>(),
        [
            (JsonNodeKind::Error, prefix.len()..end),
            (JsonNodeKind::Number, end + 4..end + 6),
            (JsonNodeKind::CloseBracket, end + 6..end + 7),
        ]
    );
    assert_eq!(doc.diagnostic().unwrap().range, end..end);
    assert_eq!(doc.reuse_stats(), Default::default());

    // A local fallback tree does not retain the strict prefix, even when a
    // later edit repairs the error without touching the prefix.
    let edit = ChangeSet::single(Change::new(prefix.len()..end, "null,")).unwrap();
    let repaired = doc.reparse(&edit).unwrap();
    assert!(repaired.diagnostic().is_none());
    assert_eq!(repaired.reuse_stats(), Default::default());
    assert_eq!(repaired.reused_suffix_actions(), 0);
}
